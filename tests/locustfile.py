"""NFR-001: 95% of normal complaint-management requests complete within 10 seconds.

Defined test load: 50 concurrent users, ramp 5 users/s, 5 minutes.

Prepare: a running instance of the app, one resident account, and one active category id.

    export LT_EMAIL=load.resident@example.com
    export LT_PASSWORD=...
    export LT_CATEGORY_ID=<uuid of an active category>
    locust -f locustfile.py --headless -u 50 -r 5 -t 5m \
        --host http://localhost:5000 --csv nfr001

The run exits non-zero if the overall p95 is above 10 seconds or any request fails.
"""
import os
import uuid

from locust import HttpUser, between, events, task

LOGIN_URL = "/api/auth/login"  # adjust to your real login route
P95_LIMIT_MS = 10_000


class Resident(HttpUser):
    wait_time = between(1, 3)

    def on_start(self):
        response = self.client.post(
            LOGIN_URL,
            json={"email": os.environ["LT_EMAIL"], "password": os.environ["LT_PASSWORD"]},
        )
        response.raise_for_status()

    @task(4)
    def list_my_complaints(self):
        self.client.get("/api/complaints", name="GET /api/complaints")

    @task(1)
    def notifications(self):
        self.client.get("/api/notifications", name="GET /api/notifications")

    @task(2)
    def submit_complaint(self):
        self.client.post(
            "/api/complaints",
            json={
                "title": "Load test complaint",
                "category_id": os.environ["LT_CATEGORY_ID"],
                "description": "Generated by the NFR-001 load test.",
                "location": "Block A",
            },
            headers={"Idempotency-Key": str(uuid.uuid4())},
            name="POST /api/complaints",
        )


@events.quitting.add_listener
def enforce_nfr_001(environment, **_):
    total = environment.stats.total
    p95 = total.get_response_time_percentile(0.95)
    if total.num_failures:
        print(f"NFR-001 FAIL: {total.num_failures} failed requests")
        environment.process_exit_code = 1
    elif p95 is not None and p95 > P95_LIMIT_MS:
        print(f"NFR-001 FAIL: p95 {p95:.0f} ms exceeds {P95_LIMIT_MS} ms")
        environment.process_exit_code = 1
    else:
        print(f"NFR-001 PASS: p95 {p95:.0f} ms")